import Foundation

/// The shared keep-best quality kernel (SCAN_PIPELINE.md §7, DESIGN.md §5.8):
/// sharpness + face quality + saliency composition + resolution, z-scored
/// WITHIN the cluster. Degenerate statistics are defined, not improvised.
public enum KeepBestKernel {
    public struct Weights: Sendable {
        public var sharpness = 0.4
        public var face = 0.3
        public var composition = 0.2
        public var resolution = 0.1
        public init() {}
    }

    /// Per-signal ε floors (population σ below which a component carries no
    /// information — values to be regenerated by the fixture harness).
    public struct EpsilonFloors: Sendable {
        public var sharpness = 1.0 // Laplacian variance units
        public var face = 0.01
        public var composition = 0.005
        public var resolution = 0.01 // megapixels
        public init() {}
    }

    public struct Member: Sendable {
        public let id: String
        public let sharpness: Double? // Laplacian variance
        public let faceCount: Int?
        public let bestFaceQuality: Double?
        public let eyesOpenMin: Double? // 0…1; nil = no face data
        public let saliencyArea: Double? // composition proxy
        public let megapixels: Double
        public let isFavorite: Bool
        public let isEdited: Bool
        public let capturedAt: Date?

        public init(
            id: String,
            sharpness: Double?,
            faceCount: Int?,
            bestFaceQuality: Double?,
            eyesOpenMin: Double?,
            saliencyArea: Double?,
            megapixels: Double,
            isFavorite: Bool = false,
            isEdited: Bool = false,
            capturedAt: Date? = nil
        ) {
            self.id = id
            self.sharpness = sharpness
            self.faceCount = faceCount
            self.bestFaceQuality = bestFaceQuality
            self.eyesOpenMin = eyesOpenMin
            self.saliencyArea = saliencyArea
            self.megapixels = megapixels
            self.isFavorite = isFavorite
            self.isEdited = isEdited
            self.capturedAt = capturedAt
        }
    }

    public enum ReasonChip: String, Sendable, Codable {
        case sharpest
        case eyesOpen = "eyes_open"
        case bestComposition = "best_composition"
        case highestResolution = "highest_resolution"
    }

    public struct Result: Sendable {
        /// nil ⟺ humility: no non-degenerate component survived — the card must
        /// use the "pick your favorite" layout (DESIGN.md §9.7).
        public let keeperId: String?
        public let scores: [String: Double]
        public let keeperChips: [ReasonChip]
        public var isHumility: Bool { keeperId == nil }
    }

    public static func evaluate(
        _ members: [Member],
        weights: Weights = Weights(),
        floors: EpsilonFloors = EpsilonFloors()
    ) -> Result {
        guard members.count >= 2 else {
            return Result(keeperId: members.first?.id, scores: [:], keeperChips: [])
        }

        let eyesClosedPenalty = 0.5

        // faceScore per member: mixed clusters — faceless members take the
        // cluster-minimum faceScore; eyesOpenMin defaults to 1 where no face exists.
        let rawFaceScores: [Double?] = members.map { member in
            guard let quality = member.bestFaceQuality else { return nil }
            let eyes = member.eyesOpenMin ?? 1.0
            return quality - eyesClosedPenalty * (1.0 - eyes)
        }
        let clusterHasFaces = rawFaceScores.contains { $0 != nil }
        let minFaceScore = rawFaceScores.compactMap { $0 }.min() ?? 0
        let faceScores: [Double]? = clusterHasFaces
            ? rawFaceScores.map { $0 ?? minFaceScore }
            : nil

        let sharpnessValues: [Double]? = members.allSatisfy { $0.sharpness == nil }
            ? nil : members.map { $0.sharpness ?? 0 }
        let compositionValues: [Double]? = members.allSatisfy { $0.saliencyArea == nil }
            ? nil : members.map { $0.saliencyArea ?? 0 }
        let resolutionValues: [Double] = members.map(\.megapixels)

        // Z-score with population σ and ε floor; σ < ε ⇒ zeros (no vote).
        func zScores(_ values: [Double], epsilon: Double) -> [Double]? {
            let count = Double(values.count)
            let mean = values.reduce(0, +) / count
            let variance = values.reduce(0) { $0 + ($1 - mean) * ($1 - mean) } / count
            let sigma = variance.squareRoot()
            guard sigma >= epsilon else { return nil } // degenerate: no information
            return values.map { ($0 - mean) / sigma }
        }

        var components: [(weight: Double, z: [Double], chip: ReasonChip)] = []
        if let values = sharpnessValues, let z = zScores(values, epsilon: floors.sharpness) {
            components.append((weights.sharpness, z, .sharpest))
        }
        if let values = faceScores, let z = zScores(values, epsilon: floors.face) {
            components.append((weights.face, z, .eyesOpen))
        }
        if let values = compositionValues, let z = zScores(values, epsilon: floors.composition) {
            components.append((weights.composition, z, .bestComposition))
        }
        if let z = zScores(resolutionValues, epsilon: floors.resolution) {
            components.append((weights.resolution, z, .highestResolution))
        }

        // No non-degenerate component ⇒ the kernel must not crown a keeper.
        guard !components.isEmpty else {
            return Result(keeperId: nil, scores: [:], keeperChips: [])
        }

        // Renormalize surviving weights to sum 1.
        let totalWeight = components.reduce(0) { $0 + $1.weight }
        var scores = [Double](repeating: 0, count: members.count)
        for component in components {
            let weight = component.weight / totalWeight
            for index in 0..<members.count {
                scores[index] += weight * component.z[index]
            }
        }

        // Deterministic winner: score, then favorite > edited > earliest capture > id.
        var bestIndex = 0
        for index in 1..<members.count {
            if isBetter(index: index, than: bestIndex, scores: scores, members: members) {
                bestIndex = index
            }
        }

        // Reason chips: every component where the keeper strictly beats the runner-up.
        var chips: [ReasonChip] = []
        for component in components {
            let keeperZ = component.z[bestIndex]
            let bestOtherZ = component.z.enumerated()
                .filter { $0.offset != bestIndex }
                .map(\.element)
                .max() ?? -.infinity
            if keeperZ > bestOtherZ {
                chips.append(component.chip)
            }
        }

        var scoreMap: [String: Double] = [:]
        for (index, member) in members.enumerated() {
            scoreMap[member.id] = scores[index]
        }
        return Result(keeperId: members[bestIndex].id, scores: scoreMap, keeperChips: chips)
    }

    private static func isBetter(index: Int, than other: Int, scores: [Double], members: [Member]) -> Bool {
        if scores[index] != scores[other] { return scores[index] > scores[other] }
        let a = members[index]
        let b = members[other]
        if a.isFavorite != b.isFavorite { return a.isFavorite }
        if a.isEdited != b.isEdited { return a.isEdited }
        let dateA = a.capturedAt ?? .distantFuture
        let dateB = b.capturedAt ?? .distantFuture
        if dateA != dateB { return dateA < dateB }
        return a.id < b.id
    }
}
